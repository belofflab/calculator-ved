"""Reference freight rate cards.

International corridors are priced in USD per chargeable kg, domestic legs in
RUB per chargeable kg.  Figures are 2025–2026 market benchmarks for consolidated
(LTL/сборный) cargo and must be refreshed from live forwarder quotes for
production use.  ``CARGO_ALL_IN`` cards already include the cargo company's
simplified clearance and handling; ``WHITE_FREIGHT`` cards are pure transport
plus hub handling and are combined with official customs clearance.
"""

