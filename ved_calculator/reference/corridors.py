def _leg(
    from_hub: str,
    city: str,
    mode: TransportMode,
    rate: str,
    min_charge: str,
    days: tuple[int, int],
    distance_km: int | None,
    *,
    coefficient: str | None = None,
    notes: str = "",
) -> DomesticLegRate:
    coef = coefficient or ("167" if mode is TransportMode.AIR else "250")
    return DomesticLegRate(
        leg_id=f"{from_hub[:3].upper()}-{city.upper()}-{mode.value}",
        from_hub=from_hub,
        destination_city=city,
        transport_mode=mode,
        rate_per_kg_rub=Decimal(rate),
        min_charge_rub=Decimal(min_charge),
        volumetric_coefficient_kg_per_m3=Decimal(coef),
        days_min=days[0],
        days_max=days[1],
        distance_km=distance_km,
        notes=notes,
    )


