def _card(
    corridor_id: str,
    origin: OriginCountry,
    origin_hub: str,
    destination_hub: str,
    mode: TransportMode,
    kind: ServiceKind,
    rate: str,
    min_charge: str,
    coefficient: str,
    days: tuple[int, int],
    *,
    handling_fixed: str = "0",
    handling_per_kg: str = "0",
    multipliers: dict[CargoCategory, Decimal] | None = None,
    notes: str = "",
) -> CorridorRateCard:
    return CorridorRateCard(
        corridor_id=corridor_id,
        origin=origin,
        origin_hub=origin_hub,
        destination_hub=destination_hub,
        transport_mode=mode,
        service_kind=kind,
        rate_per_kg_usd=Decimal(rate),
        min_charge_usd=Decimal(min_charge),
        volumetric_coefficient_kg_per_m3=Decimal(coefficient),
        handling_fixed_usd=Decimal(handling_fixed),
        handling_per_kg_usd=Decimal(handling_per_kg),
        days_min=days[0],
        days_max=days[1],
        category_multipliers=multipliers or {},
        notes=notes,
    )


